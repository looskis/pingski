#!/bin/sh
# Regenerates Sources/pingski/OpenAPISpec.swift from openapi/openapi.json.
set -eu
cd "$(dirname "$0")/.."
python3 -I -c 'import json,sys; json.load(open(sys.argv[1]))' openapi/openapi.json
{
  echo "// GENERATED by scripts/embed-openapi.sh from openapi/openapi.json. Do not edit by hand."
  echo "enum OpenAPISpec {"
  echo '    static let json = #"""'
  cat openapi/openapi.json
  echo '"""#'
  echo "}"
} > Sources/pingski/OpenAPISpec.swift
echo "embedded openapi/openapi.json into Sources/pingski/OpenAPISpec.swift"
